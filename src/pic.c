void pic_init() {

    // start init
    outb(0x20, 0x11);
    outb(0xA0, 0x11);

    // offsets
    outb(0x21, 0x20);
    outb(0xA1, 0x28);

    // wiring
    outb(0x21, 0x04);
    outb(0xA1, 0x02);

    // mode
    outb(0x21, 0x01);
    outb(0xA1, 0x01);

    // enable IRQ0 + IRQ1
    outb(0x21, 0xFC);
    outb(0xA1, 0xFF);
}